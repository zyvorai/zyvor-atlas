/// `GET /ai/anomalies` — robust local anomaly detection over persisted Atlas metrics. Uses a
/// median/MAD baseline so a previous spike cannot drag the baseline toward itself.
pub(crate) async fn ai_anomalies(
    State(s): State<AppState>,
    Extension(actor): Extension<Actor>,
    Query(q): Query<AnomalyQuery>,
) -> AppResult<Json<AnomaliesResponse>> {
    Ok(Json(
        compute_anomalies(&s, &actor, q.minutes, q.sensitivity, q.mode).await?,
    ))
}

/// Shared behind `GET /ai/anomalies` and the `detect_anomalies` MCP tool
/// (`crates/atlas-gateway/src/mcp.rs`) — one code path for role-check, validation, and detection,
/// so the MCP edge can't drift from REST (mirrors `compute_advisor`).
pub(crate) async fn compute_anomalies(
    s: &AppState,
    actor: &Actor,
    minutes: i64,
    sensitivity: f64,
    mode: AdvisorMode,
) -> AppResult<AnomaliesResponse> {
    crate::auth::require_role(s.config.auth_required, actor, crate::auth::ROLE_OPERATOR)?;
    if !(15..=20_160).contains(&minutes) {
        return Err(AppError::Validation(
            "minutes must be between 15 and 20160".into(),
        ));
    }
    if !sensitivity.is_finite() || !(2.0..=10.0).contains(&sensitivity) {
        return Err(AppError::Validation(
            "sensitivity must be a finite number between 2 and 10".into(),
        ));
    }
    let history = atlas_inventory::metrics::history(&s.pool, minutes).await?;
    let now = chrono::Utc::now();
    let (telemetry_status, latest_sample_age_minutes, mut warnings) =
        anomaly_freshness(&history, now);
    let mut anomalies = if telemetry_status == "fresh" && history.len() >= 5 {
        detect_anomalies(&history, sensitivity)
    } else {
        Vec::new()
    };
    anomalies.sort_by(|a, b| b.score.total_cmp(&a.score));
    if history.len() < 5 {
        warnings.push(format!(
            "At least 5 samples are required; {} available",
            history.len()
        ));
    }
    let (narrative_mode, narrative) = if anomalies.is_empty() {
        (None, None)
    } else {
        narrate_with(
            ProviderConfig::from_env(),
            mode,
            "anomaly",
            ANOMALY_NARRATIVE_SYSTEM,
            350,
            &json!({
                "window_minutes": minutes,
                "telemetry_status": telemetry_status,
                "sensitivity": sensitivity,
                "anomalies": anomalies,
            }),
        )
        .await?
    };
    Ok(AnomaliesResponse {
        generated_at: now.to_rfc3339(),
        window_minutes: minutes,
        sample_count: history.len(),
        telemetry_status,
        latest_sample_age_minutes,
        sensitivity,
        model: "robust_median_mad_v1",
        anomalies,
        warnings,
        narrative_mode,
        narrative,
        can_execute: false,
    })
}

