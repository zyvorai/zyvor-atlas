#[derive(Debug, Serialize)]
pub(crate) struct IncidentsResponse {
    generated_at: String,
    count: usize,
    incidents: Vec<CorrelatedIncident>,
    /// "local" (default — no narrative), "llm" (provider narrated it), "local_fallback" (provider
    /// configured but failed and `mode=auto`), or `null` when `narrative` itself is `null`.
    narrative_mode: Option<&'static str>,
    /// Plain-English root-cause paragraph over `incidents`, only present when `mode=auto`/`llm`
    /// was requested AND a provider is configured (`ATLAS_AI_BASE_URL`/`ATLAS_AI_MODEL`) — never
    /// generated by default, since this is a real external-network call with a real cost that a
    /// dashboard polling this endpoint shouldn't trigger silently.
    narrative: Option<String>,
    can_execute: bool,
}

#[derive(Debug, Deserialize)]
pub(crate) struct IncidentsQuery {
    /// Defaults to `local` here (unlike the advisor's own `auto` default) — narration is strictly
    /// opt-in for this GET endpoint. Pass `?mode=auto` (falls back silently on provider failure)
    /// or `?mode=llm` (errors if unconfigured/unavailable) to request one.
    #[serde(default = "default_incidents_mode")]
    mode: AdvisorMode,
}

fn default_incidents_mode() -> AdvisorMode {
    AdvisorMode::Local
}

